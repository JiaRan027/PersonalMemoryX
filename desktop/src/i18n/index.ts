export function t(source: string, values: Record<string, string | number> = {}): string {
  const template = activeLocale.value === "en-US" ? (messages[source] ?? source) : source
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  )
}

export function setLocale(locale: AppLocale) {
  activeLocale.value = locale
  document.documentElement.lang = locale
}

export async function initializeLocale(): Promise<void> {
  try {
    const preferences = await invoke<DesktopPreferences>("get_desktop_preferences")
    setLocale(preferences.locale === "en-US" ? "en-US" : "zh-CN")
  } catch {
    setLocale("zh-CN")
  }
}

export function useI18n() {
  return {
    locale: readonly(activeLocale),
    isEnglish: computed(() => activeLocale.value === "en-US"),
    setLocale,
    t,
  }
}
